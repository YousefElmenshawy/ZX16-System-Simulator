.org 0x0020
main:
    li16 sp, STACK_TOP # Initialize stack pointer
    li16 s0, TILE_MAP_BUFFER_ADDR
    addi s0, 63
    addi s0, 63
    addi s0, 14
    mv s1, s0
    addi s1, 19
    loop:
    call read_input
    j loop
    ecall 0xA
 read_input:	
    ecall 0x7
    li t0, 0
    beq a1, t0, no_key
    li t0, 22
    li t1, 63
    addi t1, 10
    beq a0, t0, p1up
    ecall 0x7
    beq a0, t1, p2up 
    ret   	    

no_key:
    ret

p1up:
    addi s0, 20
    li t0, 0
    sw t0, 0(s0)
    addi s0, -60
    addi t0, 2
    sw t0, 0(s0)
    addi s0, 20
    j loop                   # Jump back to loop

p2up:
    addi s1, 20
    li t0, 0
    sw t0, 0(s1)
    addi s1, -60
    addi t0, 3
    sw t0, 0(s1)
    addi s1, 20
    j loop                   # Jump back to loop



