.equ STACK_TOP, 0xFF34
.equ TILE_MAP_BUFFER_ADDR, 0xF000
.equ TILE_MAP_END, 0xF12B
.equ TILE_DEFINITIONS_ADDR, 0xF200
.equ COLOR_PALLETE_ADDR, 0xFA00


.text
.org 0x0000
j main
.org 0x0020
main:
   li16 sp, STACK_TOP # Initialize stack pointer
   li16 s0, TILE_MAP_BUFFER_ADDR
   addi s0, 63
   addi s0, 63
   addi s0, 14
   mv t0, s0
   addi t0, 10
   mv s1, s0
   addi s1, 19






   loop:

   call move_ball

   call read_input




   j loop
   ecall 0xA

read_input:
   addi sp, -4
   sw t0, 0(sp)    # save ball position
   sw ra, 2(sp)    # save return address

   ecall 0x7
   li t0, 0
   bne a1, t0, key

   lw ra, 2(sp)    # restore return address
   lw t0, 0(sp)    # restore ball position
   addi sp, 4
   ret

key:
   li t0, 22
   li t1, 63
   addi t1, 10
   bne a0, t0, L1
   call p1up
   L1:
   bne a0, t1, L2
   call p2up
   L2:
   li t1, 63
   addi t1, 11
   bne a0, t1, L3
   call p2down
   L3:
   li t1, 18
   bne a0, t1, L4
   call p1down
   L4:
   lw ra, 2(sp)    # restore return address
   lw t0, 0(sp)    # restore ball position
   addi sp, 4
   ret


p2up:
   li16 t0, TILE_MAP_BUFFER_ADDR
   addi t0, 40
   blt s1, t0, B2
   addi s1, 20
   li t1, 0
   sb t1, 0(s1)
   addi s1, -60
   addi t1, 3
   sb t1, 0(s1)
   addi s1, 20
   B2:
       ret


p1up:
   li16 t0, TILE_MAP_BUFFER_ADDR
   beq s0, t0, B1
   addi s0, 40
   li t0, 0
   sb t0, 0(s0)
   addi s0, -60
   addi t0, 2
   sb t0, 0(s0)
   B1:


   ret                  # Jump back to loop




p1down:
   li16 t0, TILE_MAP_END
   addi t0, -40  # Equivalent boundary check for bottom
   bge s0, t0, B3
   addi s0, -20
   li t1, 0
   sb t1, 0(s0)
   addi s0, 60
   addi t1, 2
   sb t1, 0(s0)
   addi s0, -20
   B3:
   ret


p2down:
   li16 t0, TILE_MAP_END
   addi t0, -21  # Equivalent boundary check for bottom
   bge s1, t0, B4
   addi s1, -20
   li t1, 0
   sb t1, 0(s1)
   addi s1, 60
   addi t1, 3
   sb t1, 0(s1)
   addi s1, -20
   B4:
   ret

move_ball:
 addi sp, -4
 sw ra, 0(sp)    # store return address
 sw t0, 2(sp)    # store current position of the ball
 li t0, 0
 beq a0, t0, Up
 lw t0, 2(sp)    # restore position of the ball
    Down:
 call move_down
 lw ra, 0(sp)    # restore return address
 addi sp, 4      # restore full stack allocation
 ret
    Up:
 lw t0, 2(sp)    # restore position of the ball
 call move_up
 lw ra, 0(sp)    # restore return address
 addi sp, 4      # restore full stack allocation
 ret


move_up:
   li16 t1, TILE_MAP_BUFFER_ADDR
   addi t1,20
   blt t0, t1, B1M
   li t1, 0
   sb t1, 0(t0)
   addi t0, -20
   addi t1, 1
   sb t1, 0(t0)
   li a0, 0     # Indicate ball moved up
   ret
   B1M:
 addi sp, -2
 sw ra, 0(sp)
   call move_down
 lw ra, 0(sp)
 addi sp, 2               # Jump back to loop
 ret




move_down:
   li16 t1, TILE_MAP_END
   addi t1, -21  # Equivalent boundary check for bottom
   bge t0, t1, B2M
   li t1, 0
   sb t1, 0(t0)
   addi t0, 20
   addi t1, 1
   sb t1, 0(t0)
   li a0, 1     # Indicate ball moved down
   ret
   B2M:

 addi sp, -2
 sw ra, 0(sp)
   call move_up
 lw ra, 0(sp)
 addi sp, 2
   ret                  # Jump back to loop




move_left:

   addi t1, 0
   li t1, 0
   sb t1, 0(t0)
   addi t0, -1
   addi t1, 1
   sb t1, 0(t0)
   ret


move_right:
   addi t1, 0
   li t1, 0
   sb t1, 0(t0)
   addi t0, 1
   addi t1, 1
   sb t1, 0(t0)
   ret








