    loop:
    call read_input
   # call move_ball
    j loop
    ecall 0xA

 read_input:
    ecall 0x7
    li t0, 0
    bne a1, t0, key
    ret
    key:
    li t0, 22
    li t1, 63
    addi t1, 10
    bne a0, t0, L1
    addi sp, -2
    sw ra, 0(sp)
    call p1up
    lw ra, 0(sp)
    addi sp, 2
    L1:
    bne a0, t1, L2
    addi sp, -2
    sw ra, 0(sp)
    call p2up
    lw ra, 0(sp)
    addi sp, 2
    L2:
    li t1, 63
    addi t1, 11
    bne a0, t1, L3
    addi sp, -2
    sw ra, 0(sp)
    call p2down
    lw ra, 0(sp)
    addi sp, 2
    L3:
    li t1, 18
    bne a0, t1, L4
    addi sp, -2
    sw ra, 0(sp)
    call p1down
    lw ra, 0(sp)
    addi sp, 2
    L4:
    ret


p2up:
    li16 t0, TILE_MAP_BUFFER_ADDR
    addi t0, 40
    blt s1, t0, B2
    addi s1, 20
    li t1, 0
    sb t1, 0(s1)
    addi s1, -60
    addi t1, 3
    sb t1, 0(s1)
    addi s1, 20
    B2:
        ret

p1up:
    li16 t0, TILE_MAP_BUFFER_ADDR
    beq s0, t0, B1
    addi s0, 40
    li t0, 0
    sb t0, 0(s0)
    addi s0, -60
    addi t0, 2
    sb t0, 0(s0)
    B1:

    ret                  # Jump back to loop


p1down:
    li16 t0, TILE_MAP_END
    addi t0, -40  # Equivalent boundary check for bottom
    bge s0, t0, B3
    addi s0, -20
    li t1, 0
    sb t1, 0(s0)
    addi s0, 60
    addi t1, 2
    sb t1, 0(s0)
    addi s0, -20
    B3:
    ret

p2down:
    li16 t0, TILE_MAP_END
    addi t0, -21  # Equivalent boundary check for bottom
    bge s1, t0, B4
    addi s1, -20
    li t1, 0
    sb t1, 0(s1)
    addi s1, 60
    addi t1, 3
    sb t1, 0(s1)
    addi s1, -20
    B4:
    ret

